using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace UI.InvokeSourceGenerator
{
    /// <summary>
    /// 扫描带 [UIInvoke] / [UIListenerInvoke] 的静态方法，为每个方法生成一个 Handler System 类，
    /// 嵌套进宿主的 static partial 类里，供 UIInvokeSystem / UIListenerInvokeSystem 反射注册。
    /// 用于替换原先预编译、源码不在仓库内（无法随改名重建）的 RD.UI.InvokeSourceGenerator.dll。
    /// </summary>
    [Generator]
    public class UIInvokeSystemGenerator : ISourceGenerator
    {
        //宿主标记特性 -> 产出到 System 类上的特性
        private static readonly Dictionary<string, string> SystemAttributes = new Dictionary<string, string>
        {
            // [UIInvoke] / [UIListenerInvoke] 定义在 RD.Core 命名空间（UIInvokeAttribute.cs / UIListenerInvokeAttribute.cs）。
            // 之前写成 "RD.UIInvokeAttribute" 时字典查不到，导致 SG 永远静默跳过、不生成任何 invoker，
            // 运行期 UIInvokeSystem.GetInvoker 全部报 "未找到UIInvoke实现"。修正全名后即可正常生成。
            { "RD.Core.UIInvokeAttribute",         "UIInvokeSystem" },
            { "RD.Core.UIListenerInvokeAttribute", "UIListenerInvokeSystem" },
        };

        public void Initialize(GeneratorInitializationContext context)
        {
            context.RegisterForSyntaxNotifications(() => new SyntaxReceiver());
        }

        public void Execute(GeneratorExecutionContext context)
        {
            if (!(context.SyntaxContextReceiver is SyntaxReceiver receiver)) return;

            //按宿主类聚合成一个文件：同一宿主类的多个 Invoke 方法合并到同一个 partial 里
            var groups = receiver.Invokes
                    .GroupBy(i => i.Key)
                    .Select(g => g.GroupBy(i => i.ClassName).Select(x => x.First()).ToList())
                    .OrderBy(list => list[0].Key, StringComparer.Ordinal)
                    .ToList();

            foreach (var list in groups)
            {
                var host = list[0];

                var sb = new StringBuilder();
                sb.AppendLine("// <auto-generated/>");
                sb.AppendLine("// 由 RD.UI.InvokeSourceGenerator 自动生成 请勿修改");
                sb.AppendLine("using RD;");
                // UIInvokeSystemAttribute / UIInvokeReturnHandler 均在 RD.Core 命名空间，缺这行会 CS0246
                sb.AppendLine("using RD.Core;");
                sb.AppendLine();
                sb.AppendLine($"namespace {host.Namespace}");
                sb.AppendLine("{");
                sb.AppendLine($"    public static partial class {host.HostClass}");
                sb.AppendLine("    {");

                for (var i = 0; i < list.Count; i++)
                {
                    if (i > 0) sb.AppendLine();

                    var info = list[i];
                    sb.AppendLine($"        [{info.SystemAttribute}(\"{info.InvokeType}\")]");
                    sb.AppendLine($"        public class {info.ClassName} : {info.MethodType}<{info.ArgsTypes}>");
                    sb.AppendLine("        {");
                    sb.AppendLine($"            protected override {info.ReturnType} Invoke({info.ArgsTypesVars})");
                    sb.AppendLine("            {");
                    sb.AppendLine($"                {info.ReturnPrefix}{info.SelfVar}.{info.MethodName}({info.ArgsWithoutSelf});");
                    sb.AppendLine("            }");
                    sb.AppendLine("        }");
                }

                sb.AppendLine("    }");
                sb.AppendLine("}");

                var hintName = $"{host.Namespace.Replace('.', '_')}_{host.HostClass}.UIInvokeSystems.g.cs";
                context.AddSource(hintName, SourceText.From(sb.ToString(), Encoding.UTF8));
            }
        }

        private class SyntaxReceiver : ISyntaxContextReceiver
        {
            public List<InvokeInfo> Invokes { get; } = new List<InvokeInfo>();

            public void OnVisitSyntaxNode(GeneratorSyntaxContext context)
            {
                if (!(context.Node is MethodDeclarationSyntax methodSyntax)) return;
                if (!(context.SemanticModel.GetDeclaredSymbol(methodSyntax) is IMethodSymbol method)) return;

                if (!method.IsStatic || method.MethodKind != MethodKind.Ordinary) return;

                //宿主必须是 static partial 类，否则产出的 partial 无法与既有声明合并
                var host = method.ContainingType;
                if (host == null || !host.IsStatic) return;
                if (methodSyntax.Parent is ClassDeclarationSyntax hostSyntax &&
                    !hostSyntax.Modifiers.Any(m => m.IsKind(SyntaxKind.PartialKeyword))) return;

                var namespaceName = host.ContainingNamespace == null || host.ContainingNamespace.IsGlobalNamespace
                        ? null
                        : host.ContainingNamespace.ToDisplayString();
                if (string.IsNullOrEmpty(namespaceName)) return;

                foreach (var attribute in method.GetAttributes())
                {
                    var attributeName = attribute.AttributeClass?.ToDisplayString();
                    if (attributeName == null || !SystemAttributes.TryGetValue(attributeName, out var systemAttribute))
                        continue;

                    //没写实参时 SG 取方法名（见 UIInvokeAttribute 的注释约定）
                    var invokeType = GetStringArgument(attribute);
                    if (string.IsNullOrEmpty(invokeType)) invokeType = method.Name;

                    var parameters = method.Parameters;
                    if (parameters.Length == 0) return;

                    //第一个参数必须是 Entity，才能套进 UIInvokeHandler<T,...> 的 where T : Entity
                    var selfType = parameters[0].Type;
                    if (!IsEntity(selfType)) return;

                    var hasReturn = method.ReturnType != null && method.ReturnType.SpecialType != SpecialType.System_Void;

                    var argTypes = parameters.Select(p => p.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)).ToList();
                    var argVars  = parameters.Select(p => VarName(p)).ToList();

                    //返回类型排在泛型最后：UIInvokeReturnHandler<T, P1, ..., R>
                    if (hasReturn) argTypes.Add(method.ReturnType!.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat));

                    var underLine = string.Join("_",
                            parameters.Select(p => Identifier(p.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat))));

                    Invokes.Add(new InvokeInfo(
                        namespaceName!,
                        host.Name,
                        systemAttribute,
                        invokeType!,
                        method.Name,
                        $"{underLine}_{method.Name}System",
                        hasReturn ? "UIInvokeReturnHandler" : "UIInvokeHandler",
                        hasReturn ? method.ReturnType!.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat) : "void",
                        hasReturn ? "return " : "",
                        string.Join(", ", argTypes),
                        string.Join(", ", argTypes.Take(parameters.Length).Zip(argVars, (t, v) => $"{t} {v}")),
                        argVars[0],
                        string.Join(", ", argVars.Skip(1))));

                    return;
                }
            }

            private static bool IsEntity(ITypeSymbol type)
            {
                for (var current = type; current != null; current = current.BaseType)
                {
                    // Entity 定义在 RD.Core 命名空间（Packages/cn.rendu.core/.../Entity.cs）。
                    // 之前写成 "RD.Entity" 时永远匹配不上，导致所有 [UIInvoke] 方法被跳过、SG 零输出。
                    if (current.ToDisplayString() == "RD.Core.Entity") return true;
                }

                return false;
            }

            private static string? GetStringArgument(AttributeData attribute)
            {
                if (attribute.ConstructorArguments.Length == 0) return null;
                return attribute.ConstructorArguments[0].Value as string;
            }

            private static string VarName(IParameterSymbol parameter)
            {
                var name = parameter.Name;
                return SyntaxFacts.GetKeywordKind(name) != SyntaxKind.None ? "@" + name : name;
            }

            //类型全名 -> 可拼进类名的片段（去命名空间，非标识符字符换成 _）
            private static string Identifier(string typeName)
            {
                var name = typeName.Replace("global::", "");
                var index = name.LastIndexOf('.');
                if (index >= 0) name = name.Substring(index + 1);

                var sb = new StringBuilder();
                foreach (var c in name) sb.Append(char.IsLetterOrDigit(c) ? c : '_');
                return sb.ToString();
            }
        }

        private class InvokeInfo
        {
            public string Key            => $"{Namespace}|{HostClass}";
            public string Namespace      { get; }
            public string HostClass      { get; }
            public string SystemAttribute{ get; }
            public string InvokeType     { get; }
            public string MethodName     { get; }
            public string ClassName      { get; }
            public string MethodType     { get; }
            public string ReturnType     { get; }
            public string ReturnPrefix   { get; }
            public string ArgsTypes      { get; }
            public string ArgsTypesVars  { get; }
            public string SelfVar        { get; }
            public string ArgsWithoutSelf{ get; }

            public InvokeInfo(string namespaceName, string hostClass, string systemAttribute, string invokeType,
                    string methodName, string className, string methodType, string returnType, string returnPrefix,
                    string argsTypes, string argsTypesVars, string selfVar, string argsWithoutSelf)
            {
                Namespace       = namespaceName;
                HostClass       = hostClass;
                SystemAttribute = systemAttribute;
                InvokeType      = invokeType;
                MethodName      = methodName;
                ClassName       = className;
                MethodType      = methodType;
                ReturnType      = returnType;
                ReturnPrefix    = returnPrefix;
                ArgsTypes       = argsTypes;
                ArgsTypesVars   = argsTypesVars;
                SelfVar         = selfVar;
                ArgsWithoutSelf = argsWithoutSelf;
            }
        }
    }
}
