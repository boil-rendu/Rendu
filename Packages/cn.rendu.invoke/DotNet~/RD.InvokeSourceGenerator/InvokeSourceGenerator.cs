using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace RD.InvokeSourceGenerator
{
    /// <summary>
    /// 扫描带 [Invoke] 的静态方法，为每个方法生成一个 handler 类（嵌套进宿主的 static partial 类）。
    ///
    /// 生成物统一继承 core 的 <c>AInvokeEntityHandler&lt;InvokeArgs&lt;...&gt;[, R]&gt;</c>，
    /// 并用 <c>[Invoke("invokeType")]</c> 标记，交给 EventSystem 唯一注册表（按 argsType + long id 索引）注册。
    /// 于是不再需要独立的 UI invoke 派发体系。
    ///
    /// 参数映射：<c>OnEventXxx(this T self, P1 p1, P2 p2)</c>
    ///   → <c>AInvokeEntityHandler&lt;InvokeArgs&lt;P1,P2&gt;[, R]&gt;</c>
    ///     调用 <c>((T)entity).OnEventXxx(args.Item1, args.Item2)</c>
    /// </summary>
    [Generator]
    public class InvokeSourceGenerator : ISourceGenerator
    {
        //宿主标记特性（RD.Core.InvokeAttribute，见 Attribute/InvokeAttribute.cs）
        private const string InvokeAttributeFullName = "RD.Core.InvokeAttribute";

        //Entity 定义在 RD.Core 命名空间（Packages/cn.rendu.core/.../Entity.cs）
        private const string EntityTypeName = "global::RD.Core.Entity";

        private const string ArgsTypePrefix = "global::RD.Core.InvokeArgs";

        public void Initialize(GeneratorInitializationContext context)
        {
            context.RegisterForSyntaxNotifications(() => new SyntaxReceiver());
        }

        public void Execute(GeneratorExecutionContext context)
        {
            if (!(context.SyntaxContextReceiver is SyntaxReceiver receiver)) return;

            //按宿主类聚合成一个文件：同一宿主类的多个 Invoke 方法合并到同一个 partial 里
            var groups = receiver.Invokes
                    .GroupBy(i => i.Key)
                    .Select(g => g.GroupBy(i => i.ClassName).Select(x => x.First()).ToList())
                    .OrderBy(list => list[0].Key, StringComparer.Ordinal)
                    .ToList();

            foreach (var list in groups)
            {
                var host = list[0];

                var sb = new StringBuilder();
                sb.AppendLine("// <auto-generated/>");
                sb.AppendLine("// 由 RD.InvokeSourceGenerator 自动生成 请勿修改");
                sb.AppendLine("using RD;");
                sb.AppendLine("using RD.Core;");
                sb.AppendLine();
                sb.AppendLine($"namespace {host.Namespace}");
                sb.AppendLine("{");
                sb.AppendLine($"    public static partial class {host.HostClass}");
                sb.AppendLine("    {");

                for (var i = 0; i < list.Count; i++)
                {
                    if (i > 0) sb.AppendLine();

                    var info = list[i];
                    sb.AppendLine($"        [Invoke({StringLiteral(info.InvokeType)})]");
                    sb.AppendLine($"        public class {info.ClassName} : {info.BaseType}");
                    sb.AppendLine("        {");
                    sb.AppendLine($"            public override {info.ReturnType} Handle({EntityTypeName} entity, {info.ArgsType} args)");
                    sb.AppendLine("            {");
                    sb.AppendLine($"                {info.CallBody}");
                    sb.AppendLine("            }");
                    sb.AppendLine("        }");
                }

                sb.AppendLine("    }");
                sb.AppendLine("}");

                var hintName = $"{host.Namespace.Replace('.', '_')}_{host.HostClass}.InvokeSystems.g.cs";
                context.AddSource(hintName, SourceText.From(sb.ToString(), Encoding.UTF8));
            }
        }

        private class SyntaxReceiver : ISyntaxContextReceiver
        {
            public List<InvokeInfo> Invokes { get; } = new List<InvokeInfo>();

            public void OnVisitSyntaxNode(GeneratorSyntaxContext context)
            {
                if (!(context.Node is MethodDeclarationSyntax methodSyntax)) return;
                if (!(context.SemanticModel.GetDeclaredSymbol(methodSyntax) is IMethodSymbol method)) return;

                if (!method.IsStatic || method.MethodKind != MethodKind.Ordinary) return;

                //宿主必须是 static partial 类，否则产出的 partial 无法与既有声明合并
                var host = method.ContainingType;
                if (host == null || !host.IsStatic) return;
                if (methodSyntax.Parent is ClassDeclarationSyntax hostSyntax &&
                    !hostSyntax.Modifiers.Any(m => m.IsKind(SyntaxKind.PartialKeyword))) return;

                var namespaceName = host.ContainingNamespace == null || host.ContainingNamespace.IsGlobalNamespace
                        ? null
                        : host.ContainingNamespace.ToDisplayString();
                if (string.IsNullOrEmpty(namespaceName)) return;

                foreach (var attribute in method.GetAttributes())
                {
                    if (attribute.AttributeClass?.ToDisplayString() != InvokeAttributeFullName)
                        continue;

                    //没写实参时取方法名（见 InvokeAttribute 的注释约定）
                    var invokeType = GetStringArgument(attribute);
                    if (string.IsNullOrEmpty(invokeType)) invokeType = method.Name;

                    var parameters = method.Parameters;
                    if (parameters.Length == 0) return;

                    //第一个参数必须是 Entity，才能套进 AInvokeEntityHandler 的 Handle(Entity, A)
                    var selfType = parameters[0].Type;
                    if (!IsEntity(selfType)) return;

                    var hasReturn = method.ReturnType.SpecialType != SpecialType.System_Void;

                    //除 self 外的参数 -> InvokeArgs<...>
                    var additionalParameters = parameters.Skip(1).ToList();

                    var argsType = additionalParameters.Count == 0
                            ? ArgsTypePrefix
                            : $"{ArgsTypePrefix}<{string.Join(", ", additionalParameters.Select(p => p.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)))}>";

                    var returnType = hasReturn
                            ? method.ReturnType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)
                            : "void";

                    var baseType = hasReturn
                            ? $"AInvokeEntityHandler<{argsType}, {returnType}>"
                            : $"AInvokeEntityHandler<{argsType}>";

                    var selfTypeName = selfType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);

                    var argsAccess = additionalParameters.Count == 0
                            ? string.Empty
                            : string.Join(", ", additionalParameters.Select((p, index) => $"args.Item{index + 1}"));

                    var call = $"(({selfTypeName})entity).{method.Name}({argsAccess});";

                    var underLine = string.Join("_",
                            parameters.Select(p => Identifier(p.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat))));

                    Invokes.Add(new InvokeInfo(
                        namespaceName!,
                        host.Name,
                        invokeType!,
                        $"{underLine}_{method.Name}System",
                        baseType,
                        argsType,
                        returnType,
                        hasReturn ? "return " + call : call));

                    return;
                }
            }

            private static bool IsEntity(ITypeSymbol type)
            {
                for (var current = type; current != null; current = current.BaseType)
                {
                    // Entity 定义在 RD.Core 命名空间（Packages/cn.rendu.core/.../Entity.cs）。
                    if (current.ToDisplayString() == "RD.Core.Entity") return true;
                }

                return false;
            }

            private static string? GetStringArgument(AttributeData attribute)
            {
                if (attribute.ConstructorArguments.Length == 0) return null;
                return attribute.ConstructorArguments[0].Value as string;
            }

            //类型全名 -> 可拼进类名的片段（去命名空间，非标识符字符换成 _）
            private static string Identifier(string typeName)
            {
                var name = typeName.Replace("global::", "");
                var index = name.LastIndexOf('.');
                if (index >= 0) name = name.Substring(index + 1);

                var sb = new StringBuilder();
                foreach (var c in name) sb.Append(char.IsLetterOrDigit(c) ? c : '_');
                return sb.ToString();
            }
        }

        private static string StringLiteral(string value)
        {
            var sb = new StringBuilder("\"");
            foreach (var c in value)
            {
                switch (c)
                {
                    case '\\': sb.Append("\\\\"); break;
                    case '"':  sb.Append("\\\""); break;
                    case '\n': sb.Append("\\n");  break;
                    case '\r': sb.Append("\\r");  break;
                    case '\t': sb.Append("\\t");  break;
                    default:   sb.Append(c);      break;
                }
            }

            sb.Append('"');
            return sb.ToString();
        }

        private class InvokeInfo
        {
            public string Key         => $"{Namespace}|{HostClass}";
            public string Namespace   { get; }
            public string HostClass   { get; }
            public string InvokeType  { get; }
            public string ClassName   { get; }
            public string BaseType    { get; }
            public string ArgsType    { get; }
            public string ReturnType  { get; }
            public string CallBody    { get; }

            public InvokeInfo(string namespaceName, string hostClass, string invokeType, string className,
                    string baseType, string argsType, string returnType, string callBody)
            {
                Namespace  = namespaceName;
                HostClass  = hostClass;
                InvokeType = invokeType;
                ClassName  = className;
                BaseType   = baseType;
                ArgsType   = argsType;
                ReturnType = returnType;
                CallBody   = callBody;
            }
        }
    }
}
