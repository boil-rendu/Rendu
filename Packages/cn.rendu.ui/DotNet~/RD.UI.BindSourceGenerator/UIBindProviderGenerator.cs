using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace UI.BindSourceGenerator
{
    /// <summary>
    /// 扫描带 [UI] 特性的 UI 组件类，生成 UICodeGenerated.UIBindProvider.Get()，
    /// 供 UIBindComponent.InitAllBind 初始化全部 UI 绑定关系。
    /// 用于替换原先预编译、源码不在仓库内（无法随改名重建）的 RD.UI.BindSourceGenerator.dll。
    /// </summary>
    [Generator]
    public class UIBindProviderGenerator : ISourceGenerator
    {
        private static readonly string[] AttributeNames =
        {
            "RD.Client.UIAttribute",
        };

        public void Initialize(GeneratorInitializationContext context)
        {
            context.RegisterForSyntaxNotifications(() => new SyntaxReceiver());
        }

        public void Execute(GeneratorExecutionContext context)
        {
            if (!(context.SyntaxContextReceiver is SyntaxReceiver receiver)) return;

            var binds = receiver.Binds
                    .GroupBy(b => b.FullName)
                    .Select(g => g.First())
                    .OrderBy(b => b.FullName, StringComparer.Ordinal)
                    .ToList();

            //无绑定数据时不产出：既避免多程序集重复定义同名类型，也让"一个 UI 都没生成"暴露为编译错误
            if (binds.Count == 0) return;

            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated/>");
            sb.AppendLine("// 由 RD.UI.BindSourceGenerator 自动生成 请勿修改");
            sb.AppendLine("using RD.Client;");
            sb.AppendLine();
            sb.AppendLine("namespace UICodeGenerated");
            sb.AppendLine("{");
            sb.AppendLine("    public static class UIBindProvider");
            sb.AppendLine("    {");
            sb.AppendLine("        public static RD.Client.UIBindVo[] Get()");
            sb.AppendLine("        {");
            sb.AppendLine("            return new RD.Client.UIBindVo[]");
            sb.AppendLine("            {");

            foreach (var bind in binds)
            {
                sb.AppendLine("                new RD.Client.UIBindVo");
                sb.AppendLine("                {");
                sb.AppendLine($"                    CodeType      = {bind.CodeType},");
                sb.AppendLine($"                    ComponentType = typeof({bind.FullName}),");
                sb.AppendLine($"                    PkgName       = {bind.FullName}.PkgName,");
                sb.AppendLine($"                    ResName       = {bind.FullName}.ResName,");
                sb.AppendLine($"                    PanelLayer    = {bind.PanelLayer},");
                sb.AppendLine("                },");
            }

            sb.AppendLine("            };");
            sb.AppendLine("        }");
            sb.AppendLine("    }");
            sb.AppendLine("}");

            context.AddSource("UIBindProvider.g.cs", SourceText.From(sb.ToString(), Encoding.UTF8));
        }

        private class SyntaxReceiver : ISyntaxContextReceiver
        {
            public List<BindInfo> Binds { get; } = new List<BindInfo>();

            public void OnVisitSyntaxNode(GeneratorSyntaxContext context)
            {
                if (!(context.Node is ClassDeclarationSyntax)) return;
                if (!(context.SemanticModel.GetDeclaredSymbol(context.Node) is INamedTypeSymbol symbol)) return;

                foreach (var attribute in symbol.GetAttributes())
                {
                    var attributeName = attribute.AttributeClass?.ToDisplayString();
                    if (attributeName == null || !AttributeNames.Contains(attributeName)) continue;

                    var pkgName = GetConstString(symbol, "PkgName");
                    var resName = GetConstString(symbol, "ResName");
                    if (string.IsNullOrEmpty(pkgName) || string.IsNullOrEmpty(resName)) continue;

                    var codeType   = GetEnumArgument(attribute, 0, "EUICodeType.Common");
                    var panelLayer = GetEnumArgument(attribute, 1, "EPanelLayer.Any");

                    Binds.Add(new BindInfo(
                        symbol.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat),
                        pkgName!, resName!, codeType, panelLayer));
                    break;
                }
            }

            private static string? GetConstString(INamedTypeSymbol symbol, string name)
            {
                foreach (var member in symbol.GetMembers(name))
                {
                    if (member is IFieldSymbol field && field.IsConst && field.ConstantValue is string value)
                        return value;
                }

                return null;
            }

            private static string GetEnumArgument(AttributeData attribute, int index, string fallback)
            {
                if (index >= attribute.ConstructorArguments.Length) return fallback;

                var argument = attribute.ConstructorArguments[index];
                if (argument.Type == null || argument.Type.TypeKind != TypeKind.Enum) return fallback;

                foreach (var member in argument.Type.GetMembers())
                {
                    if (member is IFieldSymbol field && Equals(field.ConstantValue, argument.Value))
                        return $"{argument.Type.Name}.{field.Name}";
                }

                return fallback;
            }
        }

        private class BindInfo
        {
            public string FullName    { get; }
            public string PkgName     { get; }
            public string ResName     { get; }
            public string CodeType    { get; }
            public string PanelLayer  { get; }

            public BindInfo(string fullName, string pkgName, string resName, string codeType, string panelLayer)
            {
                FullName   = fullName;
                PkgName    = pkgName;
                ResName    = resName;
                CodeType   = codeType;
                PanelLayer = panelLayer;
            }
        }
    }
}
